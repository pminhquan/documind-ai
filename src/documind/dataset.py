"""Real-document dataset onboarding, validation, and prediction runs.

Default dataset root: ``data/eval/real`` (configurable). Layout:

    data/eval/real/
    ├── raw/                 user-provided originals (never committed)
    ├── anonymized/          anonymized images ready for the pipelines
    ├── ground_truth/        <id>.ocr|invoice|table.json annotations
    ├── predictions/         generated by documind-dataset predict
    ├── reports/             generated evaluation reports
    ├── manifest-<task>.json per-task eval manifests (provenance: real)
    └── README.md            dataset notes written by the owner

Everything under the real-data root stays out of Git by default
(``data/eval/real/`` is git-ignored); committing anonymized ground
truth later is an explicit, reviewed decision.

Ground truth is NEVER generated from model predictions here — the
owner annotates manually from the templates in
``data/annotation/templates/``.
"""

import json
import re
import shutil
from pathlib import Path

from .evaluation.manifest import load_manifest
from .ocr.validation import (
    DEFAULT_MAX_SIZE_BYTES,
    SUPPORTED_EXTENSIONS,
    ValidationError,
    validate_file,
)

DEFAULT_ROOT = Path("data/eval/real")
DATASET_DIRS = ("raw", "anonymized", "ground_truth", "predictions", "reports")
TASKS = ("ocr", "invoice", "table")
MANIFEST_NAME = "manifest-{task}.json"
PREDICTION_NAMES = {
    "ocr": "{id}.ocr.json",
    "invoice": "{id}.invoice.json",
    "table": "{id}.tables.json",
}
GT_SUFFIXES = {"ocr": ".ocr.json", "invoice": ".invoice.json", "table": ".table.json"}
SAFE_ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
PLACEHOLDER_RE = re.compile(r"<[a-z_][a-z_ -]*>", re.IGNORECASE)

DATASET_README = """# Real-document evaluation dataset

Provenance: **real** (declared in every generated manifest).

## Workflow

1. Copy original documents into `raw/` (never committed).
2. Anonymize them (blur/replace personal data) and save the result to
   `anonymized/<id>.<ext>` — or run
   `documind-dataset add <raw-image> --id <id> --confirm-anonymized`.
3. Annotate ground truth by hand into `ground_truth/` using the
   templates in `data/annotation/templates/`:
   `<id>.ocr.json`, `<id>.invoice.json`, `<id>.table.json`.
4. `documind-dataset validate` — fix every reported issue.
5. `documind-dataset predict --task ocr|invoice|table` (runs the local
   pipelines; needs the PaddleOCR venv).
6. `documind-eval --task <task> --manifest manifest-<task>.json`
   (paths resolve inside this directory).

## Policy

- Ground truth is annotated manually; it is never generated from
  model predictions.
- Nothing under this directory is committed by default. Committing
  anonymized ground truth is an explicit, reviewed decision.
"""


class DatasetError(ValueError):
    """Raised for invalid dataset usage (bad ids, missing files, ...)."""


def dataset_root(root: str | Path | None = None) -> Path:
    return Path(root) if root else DEFAULT_ROOT


def init_dataset(root: str | Path | None = None) -> Path:
    """Create the dataset directory layout; refuse to clobber a README."""
    base = dataset_root(root)
    readme = base / "README.md"
    if readme.exists():
        raise DatasetError(f"dataset already initialized at '{base}'")
    for name in DATASET_DIRS:
        (base / name).mkdir(parents=True, exist_ok=True)
    readme.write_text(DATASET_README, encoding="utf-8")
    return base


def add_document(image: str | Path, document_id: str, root: str | Path | None = None,
                 confirm_anonymized: bool = False) -> Path:
    """Copy an image into ``anonymized/`` under ``document_id``.

    Requires the explicit ``confirm_anonymized`` flag: the caller asserts
    personal data was removed before the copy leaves ``raw/``. Document
    ids are unique regardless of image extension, and the size limit
    matches the OCR pipeline so onboarding never accepts a file the
    pipelines would reject.
    """
    if not SAFE_ID_RE.match(document_id):
        raise DatasetError(
            f"invalid document id {document_id!r}: use letters, digits, '.', '_', '-'"
        )
    if not confirm_anonymized:
        raise DatasetError(
            "refusing to onboard a document without --confirm-anonymized: "
            "anonymize personal data first (see data/annotation/templates/ "
            "and docs/dataset-annotation-guide.md)"
        )
    base = dataset_root(root)
    if not (base / "README.md").is_file():
        raise DatasetError(
            f"dataset not initialized at '{base}': run 'documind-dataset init' first"
        )
    anonymized_dir = base / "anonymized"
    if not anonymized_dir.is_dir():
        raise DatasetError(
            f"dataset layout incomplete at '{base}': 'anonymized/' is missing — "
            "run 'documind-dataset init' to recreate the layout"
        )
    for existing in anonymized_dir.iterdir() if anonymized_dir.is_dir() else []:
        if existing.stem == document_id:
            raise DatasetError(
                f"document id already exists: '{existing.name}' — ids are "
                "unique across image formats"
            )
    source = Path(image)
    try:
        validate_file(source, extensions=SUPPORTED_EXTENSIONS,
                      max_size_bytes=DEFAULT_MAX_SIZE_BYTES)
    except ValidationError as exc:
        raise DatasetError(str(exc)) from exc
    target = anonymized_dir / f"{document_id}{source.suffix.lower()}"
    if target.exists():
        raise DatasetError(f"document already exists: '{target}'")
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, target)
    return target


def _iter_strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for key, item in value.items():
            yield from _iter_strings(key)
            yield from _iter_strings(item)
    elif isinstance(value, list):
        for item in value:
            yield from _iter_strings(item)


def _check_ground_truth(path: Path, issues: list[str]) -> bool:
    """Structural completeness checks for one annotation file."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        issues.append(f"{path.name}: malformed JSON ({exc})")
        return False
    if not isinstance(data, dict):
        issues.append(
            f"{path.name}: annotation must be a JSON object "
            f"(got {type(data).__name__})"
        )
        return False

    task = next((t for t in TASKS if path.name.endswith(GT_SUFFIXES[t])), None)
    if task is None:
        issues.append(f"{path.name}: unknown ground-truth suffix")
        return False

    for text in _iter_strings(data):
        if PLACEHOLDER_RE.search(text):
            issues.append(f"{path.name}: unresolved placeholder {text!r}")

    if task == "ocr":
        if not isinstance(data.get("reference_text"), str):
            issues.append(f"{path.name}: OCR ground truth needs a string 'reference_text'")
            return False
        return True

    if task == "invoice":
        invoice = data.get("invoice")
        if not isinstance(invoice, dict):
            issues.append(f"{path.name}: invoice ground truth needs an 'invoice' object")
            return False
        missing_keys = [
            key for key in
            ("supplier", "invoice_number", "invoice_date", "currency", "subtotal",
             "tax", "discount", "total", "payment_amount", "change_amount",
             "line_items")
            if key not in invoice
        ]
        if missing_keys:
            issues.append(f"{path.name}: invoice annotation missing keys: {missing_keys}")
            return False
        if not isinstance(invoice["line_items"], list):
            issues.append(f"{path.name}: 'line_items' must be a list")
            return False
        return True

    tables = data.get("tables")
    if not isinstance(tables, list) or not tables:
        issues.append(f"{path.name}: table ground truth needs a non-empty 'tables' list")
        return False
    ok = True
    for index, table in enumerate(tables):
        if not isinstance(table, dict):
            issues.append(
                f"{path.name}: tables[{index}] must be an object with "
                "rows/columns/cells"
            )
            ok = False
            continue
        rows, columns = table.get("rows"), table.get("columns")
        cells = table.get("cells")
        if not isinstance(rows, int) or not isinstance(columns, int):
            issues.append(f"{path.name}: tables[{index}] needs integer rows/columns")
            ok = False
            continue
        if not isinstance(cells, list) or len(cells) != rows or any(
            not isinstance(row, list) or len(row) != columns for row in cells
        ):
            issues.append(
                f"{path.name}: tables[{index}] cells matrix must be {rows}x{columns}"
            )
            ok = False
    return ok


def validate_dataset(root: str | Path | None = None) -> tuple[bool, list[str]]:
    """Validate structure and annotation completeness.

    Returns ``(ok, lines)``: human-readable lines describing coverage,
    every error found, and per-task readiness. ``ok`` is False when at
    least one error exists. Readiness ("ready to evaluate") means the
    task has annotated documents AND a valid manifest whose prediction
    files all exist AND whose entries exactly cover the annotated
    documents — annotations added after the last ``predict`` or manifest
    entries whose ground truth disappeared make the task not ready. It is
    reported separately from structural validity.
    """
    base = dataset_root(root)
    lines: list[str] = [f"dataset root: {base}"]
    errors: list[str] = []

    for name in DATASET_DIRS:
        if not (base / name).is_dir():
            errors.append(f"missing directory: {base / name}")
    if errors:
        lines += [f"ERROR {error}" for error in errors]
        lines.append("run 'documind-dataset init' first")
        return False, lines

    images = sorted(
        p for p in (base / "anonymized").iterdir()
        if p.suffix.lower() in SUPPORTED_EXTENSIONS
    )
    lines.append(f"documents in anonymized/: {len(images)}")

    # Manifests: valid ones with all prediction files present mark their
    # task as ready to evaluate.
    manifest_status: dict[str, bool] = {}
    manifest_ids: dict[str, set[str]] = {}
    for manifest_path in sorted(base.glob("manifest-*.json")):
        match = re.fullmatch(r"manifest-(.+)\.json", manifest_path.name)
        task = match.group(1) if match else None
        try:
            manifest = load_manifest(manifest_path)
        except Exception as exc:
            errors.append(f"{manifest_path.name}: invalid manifest ({exc})")
            if task in TASKS:
                manifest_status[task] = False
            continue
        missing_predictions = [
            entry.prediction.name for entry in manifest.entries
            if not entry.prediction.is_file()
        ]
        if missing_predictions:
            errors.append(
                f"{manifest_path.name}: prediction file(s) missing "
                f"({', '.join(missing_predictions)}) — run 'documind-dataset "
                "predict' to generate them"
            )
            if task in TASKS:
                manifest_status[task] = False
            continue
        lines.append(
            f"  {manifest_path.name}: valid ({len(manifest.entries)} entries, "
            f"provenance {manifest.provenance})"
        )
        if task in TASKS:
            manifest_status[task] = True
            manifest_ids[task] = {entry.id for entry in manifest.entries}

    annotated_counts: dict[str, int] = {}
    annotated_ids: dict[str, set[str]] = {}
    for task in TASKS:
        ids = {
            image.stem for image in images
            if (base / "ground_truth" / f"{image.stem}{GT_SUFFIXES[task]}").exists()
        }
        annotated_ids[task] = ids
        annotated_counts[task] = len(ids)
        lines.append(f"  {task}: {len(ids)}/{len(images)} annotated")

    # Manifest coverage must match the annotated set exactly: entries whose
    # ground truth disappeared are stale, annotations added after the last
    # predict are missing from the manifest — either way the manifest is
    # out of date and the task is not ready until predict regenerates it.
    for task in TASKS:
        if not manifest_status.get(task):
            continue
        stale = sorted(manifest_ids[task] - annotated_ids[task])
        untracked = sorted(annotated_ids[task] - manifest_ids[task])
        if not stale and not untracked:
            continue
        manifest_status[task] = False
        if stale:
            errors.append(
                f"{MANIFEST_NAME.format(task=task)}: manifest entries without "
                f"ground truth ({', '.join(stale)}) — run 'documind-dataset "
                f"predict --task {task}' to refresh the manifest"
            )
        if untracked:
            errors.append(
                f"{MANIFEST_NAME.format(task=task)}: annotated document(s) "
                f"missing from the manifest ({', '.join(untracked)}) — "
                "annotated after the last predict; run 'documind-dataset "
                f"predict --task {task}'"
            )

    for image in images:
        for task in TASKS:
            gt_path = base / "ground_truth" / f"{image.stem}{GT_SUFFIXES[task]}"
            if gt_path.exists():
                _check_ground_truth(gt_path, errors)

    lines.append("readiness:")
    for task in TASKS:
        count = annotated_counts[task]
        if count == 0:
            lines.append(f"  not ready: {task} (no annotated documents)")
        elif manifest_status.get(task):
            lines.append(f"  ready to evaluate: {task} ({count} documents)")
        else:
            lines.append(
                f"  not ready: {task} ({count} annotated document(s), no valid "
                f"manifest — run 'documind-dataset predict --task {task}')"
            )

    lines.append(f"issues found: {len(errors)}")
    lines.extend(f"ERROR {error}" for error in errors)
    return (not errors), lines


def annotated_document_ids(root: str | Path | None = None, task: str = "ocr") -> list[str]:
    """Document ids under ``anonymized/`` that have ground truth for ``task``."""
    base = dataset_root(root)
    return sorted(
        image.stem for image in (base / "anonymized").iterdir()
        if image.suffix.lower() in SUPPORTED_EXTENSIONS
        and (base / "ground_truth" / f"{image.stem}{GT_SUFFIXES[task]}").exists()
    )


def find_document_image(root: str | Path | None, document_id: str) -> Path | None:
    for image in sorted((dataset_root(root) / "anonymized").iterdir()):
        if image.stem == document_id and image.suffix.lower() in SUPPORTED_EXTENSIONS:
            return image
    return None


def build_task_manifest(root: str | Path | None = None, task: str = "ocr") -> dict:
    """Build the per-task manifest dict for annotated documents."""
    if task not in TASKS:
        raise DatasetError(f"unknown task {task!r}")
    base = dataset_root(root)
    documents = [
        {
            "id": document_id,
            "prediction": f"predictions/{PREDICTION_NAMES[task].format(id=document_id)}",
            "ground_truth": f"ground_truth/{document_id}{GT_SUFFIXES[task]}",
        }
        for document_id in annotated_document_ids(base, task)
    ]
    return {"task": task, "provenance": "real", "documents": documents}


def write_task_manifest(root: str | Path | None = None, task: str = "ocr") -> Path:
    base = dataset_root(root)
    manifest_path = base / MANIFEST_NAME.format(task=task)
    manifest_path.write_text(
        json.dumps(build_task_manifest(base, task), indent=1), encoding="utf-8"
    )
    return manifest_path
